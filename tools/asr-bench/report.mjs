#!/usr/bin/env node
// Aggregates data/results/*.json into markdown tables (data/results/summary.md).
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { normalize, align } from './lib/text.mjs';
import { GAME_HOTWORDS } from '../../src/voice/asr-presets.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const dir = join(here, 'data', 'results');
const R = readdirSync(dir).filter((f) => f.endsWith('.json')).map((f) => ({ f, ...JSON.parse(readFileSync(join(dir, f), 'utf8')) }));
const ORDER = ['zipformer-20M', 'zipformer-0621', 'kroko-en', 'nemo-fc-80ms', 'nemo-fc-480ms', 'moonshine-tiny', 'moonshine-base', 'moonshine2-tiny', 'moonshine2-base', 'whisper-tiny.en', 'whisper-base.en', 'parakeet-tdt-v2', 'two-pass'];
const byOrder = (a, b) => ORDER.indexOf(a.preset) - ORDER.indexOf(b.preset);

const q = (arr, p) => { const a = arr.filter((v) => v != null && !Number.isNaN(v)).sort((x, y) => x - y); if (!a.length) return null; const i = (a.length - 1) * p; const lo = Math.floor(i), hi = Math.ceil(i); return a[lo] + (a[hi] - a[lo]) * (i - lo); };
const f0 = (v) => (v == null ? '–' : v.toFixed(0));
const f1 = (v) => (v == null ? '–' : v.toFixed(1));
const f2 = (v) => (v == null ? '–' : v.toFixed(2));
const pct = (a, b) => (b ? (100 * a) / b : null);
const sum = (rows, k) => rows.reduce((a, r) => a + (r[k] ?? 0), 0);
const wer = (rows) => pct(sum(rows, 'err'), sum(rows, 'n'));
const kw = (rows) => pct(sum(rows, 'kwHit'), sum(rows, 'kwTotal'));
const exact = (rows) => pct(rows.filter((r) => r.exact).length, rows.length);
const MB = (b) => (b / 1e6).toFixed(0);

const hotSet = new Set(GAME_HOTWORDS.filter((h) => !h.includes(' ')).map((h) => normalize(h)[0]));
function hotRecall(rows) {
  let t = 0, h = 0;
  for (const r of rows) {
    const ref = normalize(r.ref), hyp = normalize(r.hyp);
    for (const [op, ri] of align(ref, hyp).ops) if (ri >= 0 && hotSet.has(ref[ri])) { t++; if (op === '=') h++; }
  }
  return pct(h, t);
}

let md = `# ASR bench summary (generated by report.mjs)\n\n`;
const any = R[0];
md += `sherpa-onnx-node ${any?.sherpaVersion}, Node ${any?.node}, CPU: ${any?.cpu} x${any?.nCpu}\n\n`;

// ---- accuracy
const acc = R.filter((r) => r.mode === 'accuracy' && !r.hotwords && !r.f.includes('modified_beam_search') && !r.tag).sort(byOrder);
md += `## Accuracy (push-to-talk final, all ${acc[0] ? acc[0].rows.length / 2 : 0} clips per condition, 2 threads, greedy)\n\n`;
md += `| model | files MB | WER clean | WER noisy | keyword acc clean | keyword acc noisy | exact clean | exact noisy | game-term recall (clean/noisy) | RTF (t2) | load ms | RSS loaded / peak MiB |\n|---|---|---|---|---|---|---|---|---|---|---|---|\n`;
for (const r of acc) {
  const c = r.rows.filter((x) => x.cond === 'clean'), n = r.rows.filter((x) => x.cond === 'noisy');
  const rtf = sum(r.rows, 'computeMs') / 1000 / sum(r.rows, 'audioSec');
  md += `| ${r.preset} | ${MB(r.modelBytes)} | ${f1(wer(c))}% | ${f1(wer(n))}% | ${f1(kw(c))}% | ${f1(kw(n))}% | ${f0(exact(c))}% | ${f0(exact(n))}% | ${f0(hotRecall(c))}% / ${f0(hotRecall(n))}% | ${f2(rtf)} | ${r.loadMs} | ${f0(r.rssLoadedMiB)} / ${f0(r.rssPeakMiB)} |\n`;
}
md += `\nRTF = total compute / audio fed (for offline kinds in accuracy mode only the final decode runs; partial re-decodes are extra — see latency table's CPU busy column).\n\n`;

// per-category keyword accuracy
const cats = ['create', 'followup', 'action', 'odd', 'disfluent', 'numeric', 'short'];
md += `### WER by category (clean+noisy)\n\n| model | ${cats.join(' | ')} |\n|---|${cats.map(() => '---').join('|')}|\n`;
for (const r of acc) md += `| ${r.preset} | ${cats.map((c) => f1(wer(r.rows.filter((x) => x.cat === c)))).join(' | ')} |\n`;
md += `\n### WER by voice (clean / noisy)\n\n`;
const voices = [...new Set(acc[0]?.rows.map((x) => x.voice) ?? [])];
md += `| model | ${voices.join(' | ')} |\n|---|${voices.map(() => '---').join('|')}|\n`;
for (const r of acc) md += `| ${r.preset} | ${voices.map((v) => `${f1(wer(r.rows.filter((x) => x.voice === v && x.cond === 'clean')))} / ${f1(wer(r.rows.filter((x) => x.voice === v && x.cond === 'noisy')))}`).join(' | ')} |\n`;

// ---- hotwords
const hot = R.filter((r) => r.mode === 'accuracy' && ['zipformer-20M', 'zipformer-0621', 'kroko-en', 'parakeet-tdt-v2'].includes(r.preset) && !r.tag).sort(byOrder);
md += `\n## Contextual biasing (hotwords, ${GAME_HOTWORDS.length} phrases, score 1.5)\n\n| model | decoding | WER clean | WER noisy | keyword acc clean / noisy | game-term recall clean / noisy | RTF |\n|---|---|---|---|---|---|---|\n`;
for (const r of hot) {
  const c = r.rows.filter((x) => x.cond === 'clean'), n = r.rows.filter((x) => x.cond === 'noisy');
  const how = r.hotwords ? 'MBS + hotwords' : r.f.includes('modified_beam_search') ? 'modified_beam_search' : 'greedy';
  md += `| ${r.preset} | ${how} | ${f1(wer(c))}% | ${f1(wer(n))}% | ${f1(kw(c))}% / ${f1(kw(n))}% | ${f0(hotRecall(c))}% / ${f0(hotRecall(n))}% | ${f2(sum(r.rows, 'computeMs') / 1000 / sum(r.rows, 'audioSec'))} |\n`;
}

// ---- latency
function latRow(r) {
  const rows = r.rows;
  const words = rows.flatMap((x) => x.wordLatMs);
  const wip = pct(sum(rows, 'wordsInPartial'), sum(rows, 'words'));
  const busy = sum(rows, 'pttBusyMs') / sum(rows, 'speechMs');
  return `| ${r.preset} | ${r.threads} | ${f0(q(rows.map((x) => x.firstPartialMs), 0.5))} / ${f0(q(rows.map((x) => x.firstPartialMs), 0.9))} | ${f1(q(rows.map((x) => x.partialRateHz), 0.5))} | ${f0(wip)}% | ${f0(q(words, 0.5))} / ${f0(q(words, 0.9))} | ${f0(q(rows.map((x) => x.pttFinalMs), 0.5))} / ${f0(q(rows.map((x) => x.pttFinalMs), 0.9))} / ${f0(q(rows.map((x) => x.pttFinalMs), 1))} | ${f0(q(rows.map((x) => x.hfEndpointMs), 0.5))} / ${f0(q(rows.map((x) => x.hfEndpointMs), 0.9))} | ${f0(pct(rows.filter((x) => x.hfMissed).length, rows.length))}% | ${f2(busy)} | ${f1(wer(rows))}% |\n`;
}
const latHead = `| model | thr | first partial ms p50 / p90 | partial updates /s p50 | ref words seen in a partial | word→partial latency ms p50 / p90 | PTT release→final ms p50 / p90 / max | hands-free speech end→final ms p50 / p90 | endpoint missed | CPU busy / speech time | WER (PTT) |\n|---|---|---|---|---|---|---|---|---|---|---|\n`;
for (const t of [1, 2]) {
  const lat = R.filter((r) => r.mode === 'latency' && r.threads === t && !r.tag).sort(byOrder);
  md += `\n## Latency, ${t} thread(s) (clean, ${lat[0]?.rows.length ?? 0} clips: kok-adam + libritts voices; 100 ms chunks, virtual real-time clock)\n\n` + latHead;
  for (const r of lat) md += latRow(r);
}
const rep = R.filter((r) => r.mode === 'latency' && r.tag === 'rep2').sort(byOrder);
if (rep.length) { md += `\n## Repeatability: second latency pass, 2 threads\n\n` + latHead; for (const r of rep) md += latRow(r); }
const noisy = R.filter((r) => r.mode === 'latency' && r.tag === 'noisy').sort(byOrder);
if (noisy.length) { md += `\n## Latency on noisy audio, 2 threads\n\n` + latHead; for (const r of noisy) md += latRow(r); }

writeFileSync(join(dir, 'summary.md'), md);
console.log(md);
