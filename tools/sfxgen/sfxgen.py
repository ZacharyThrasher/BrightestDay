#!/usr/bin/env python3
"""Brightest Day procedural SFX generator.

    python tools/sfxgen/sfxgen.py                 # regenerate everything -> assets/sfx/*.ogg + manifest.ron
    python tools/sfxgen/sfxgen.py --only hit_heavy construct_shatter
    python tools/sfxgen/sfxgen.py --format wav    # 16-bit PCM WAV instead (needs Bevy's "wav" feature)

Fully deterministic: every file is seeded from crc32(name, variation).
"""
from __future__ import annotations

import argparse
import sys
import time
import zlib
from pathlib import Path

import numpy as np
import soundfile as sf

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import dsp  # noqa: E402
from sounds import REGISTRY, CATEGORY_LUFS  # noqa: E402
import sounds_weapons  # noqa: E402,F401  (registers guns + ring blast)
import sounds_streak  # noqa: E402  (registers KO streak sets)
import sounds_transform  # noqa: E402,F401  (robot <-> vehicle transformations)
import sounds_ambience  # noqa: E402,F401  (world ambience beds/emitters + danger/mix cues)

ROOT = HERE.parent.parent
OUT_DIR = ROOT / 'assets' / 'sfx'
CEILING_DB = -1.0     # delivered peak ceiling
ENCODE_MARGIN_DB = 0.6  # Vorbis can overshoot the PCM master's peak by ~0.5 dB
MAX_LIMIT_DB = 7.5  # never limit harder than this; reduce gain instead


def seed_for(name: str, v: int) -> int:
    return zlib.crc32(f'brightest-day/{name}/{v}'.encode())


def master(x: np.ndarray, loop: bool, target: float, fmt: str = 'ogg', max_dur=None,
           fade_out: float = 0.02) -> tuple[np.ndarray, dict]:
    x = np.nan_to_num(np.asarray(x, float))
    x = dsp.dc_block(x, loop=loop)
    if not loop:
        x = dsp.trim(x, fade_out=fade_out)
        if max_dur and len(x) > dsp.ns(max_dur):
            x = x[:dsp.ns(max_dur)].copy()
            f = min(dsp.ns(0.15), len(x) // 3)
            w = 0.5 + 0.5 * np.cos(np.linspace(0, np.pi, f))
            x[-f:] *= w[:, None] if x.ndim == 2 else w
        x = dsp.remove_dc(x)
    ceil_db = CEILING_DB - (ENCODE_MARGIN_DB if fmt == 'ogg' else 0.0)
    ceiling = 10 ** (ceil_db / 20)
    meas = dsp.lufs_integrated(x, loop=True) if loop else dsp.lufs_momentary_max(x)
    gain_db = target - meas
    peak_db = 20 * np.log10(np.max(np.abs(x)) + 1e-12) + gain_db
    over = peak_db - ceil_db
    if loop:
        if over > 0:  # loops: never limit (keeps them smooth), just cap gain
            gain_db -= over
    elif over > MAX_LIMIT_DB:
        gain_db -= over - MAX_LIMIT_DB
    x = x * 10 ** (gain_db / 20)
    if not loop and np.max(np.abs(x)) > ceiling:
        x = dsp.remove_dc(dsp.limiter(x, ceiling * 0.99))
    final = dsp.lufs_integrated(x, loop=True) if loop else dsp.lufs_momentary_max(x)
    info = {
        'lufs': final,
        'peak_db': 20 * np.log10(np.max(np.abs(x)) + 1e-12),
        'rms_db': 10 * np.log10(np.mean(x ** 2) + 1e-20),
        'dur': len(x) / dsp.SR,
        'short_of_target': target - final,
    }
    return x, info


def write_loop(path: Path, x: np.ndarray, fmt: str, rng):
    """Loops: try the best few seam positions and keep the encode whose decoded wrap is cleanest."""
    best = None
    for i in dsp.seam_candidates(x)[:6]:
        y = np.roll(x, -i, axis=0)
        write(path, y, fmt, rng)
        d, _ = sf.read(path)
        worst = max(max(j, h / 3.0) for j, h in (dsp.seam_metrics(c) for c in dsp.chans(d)))
        if best is None or worst < best[0]:
            best = (worst, i)
        if worst < 0.5:
            return
    write(path, np.roll(x, -best[1], axis=0), fmt, rng)


def write(path: Path, x: np.ndarray, fmt: str, rng):
    if fmt == 'wav':
        tpdf = (rng.uniform(-0.5, 0.5, x.shape) + rng.uniform(-0.5, 0.5, x.shape))
        q = np.clip(np.round(x * 32767 + tpdf), -32768, 32767).astype(np.int16)
        sf.write(path, q, dsp.SR, subtype='PCM_16')
    else:
        # 16-bit master, then Vorbis ~q7 (compression_level 0.3 => libvorbis quality 0.7).
        # Lossy coding can overshoot the master's peak: decode, and trim gain until <= ceiling.
        for _ in range(4):
            q = (np.round(np.clip(x, -1, 1) * 32767) / 32767).astype(np.float32)
            ch = 1 if q.ndim == 1 else q.shape[1]
            # write in blocks: libsndfile's Vorbis encoder overflows the stack on long single writes
            with sf.SoundFile(path, 'w', dsp.SR, ch, format='OGG', subtype='VORBIS', compression_level=0.3) as f:
                for i in range(0, len(q), 16384):
                    f.write(q[i:i + 16384])
            y, _sr = sf.read(path)
            over = 20 * np.log10(np.max(np.abs(y)) + 1e-12) - (CEILING_DB - 0.05)
            if over <= 0:
                break
            x = x * 10 ** (-(over + 0.05) / 20)


def manifest(sounds, fmt: str) -> str:
    lines = [
        '// Brightest Day SFX manifest — GENERATED by tools/sfxgen/sfxgen.py, do not edit by hand.',
        '// Paths are relative to assets/. Pick a random entry of `files` per play and a random',
        '// playback speed in `pitch` (min, max) - micro variation only (about +-10..50 cents).',
        '// The LOUDNESS HIERARCHY IS BAKED INTO THE FILES: `lufs` is each sound\'s target (BS.1770 K-weighted;',
        '// one-shots on max momentary 400 ms loudness, loops on integrated loudness; peaks <= -1 dBFS), so',
        '// `volume` is always 1.0 and the mixer (buses/snapshots/distance) decides the rest.',
        '// All sounds are DRY (no baked room reverb): the mixer supplies one shared space.',
        '// `stereo: true` = a 2-channel ambience bed (play non-spatialised); everything else is mono.',
        '// Groups: ' + '; '.join(f'{k} {v}' for k, v in CATEGORY_LUFS.items()) + '.',
        '// `sequence: true` means `files` are ordered steps (KO streak: play files[step-1]), not variations;',
        '// sequences step up in loudness by 0.5 dB per step from `lufs`. See `ko_streak` at the bottom.',
        '// Suggested Rust shape:',
        '//   struct SfxManifest { sample_rate: u32, sounds: HashMap<String, SfxEntry>, ko_streak: KoStreak }',
        '//   struct SfxEntry { files: Vec<String>, category: String, volume: f32, looping: bool,',
        '//                     pitch: (f32, f32), lufs: f32, sequence: bool, #[serde(default)] stereo: bool }',
        '//   struct KoStreak { key: String, steps: Vec<String>, corps: HashMap<String, String>,',
        '//                     accents: HashMap<String, String> }',
        '(',
        f'    sample_rate: {dsp.SR},',
        '    sounds: {',
    ]
    for s in sounds:
        files = ', '.join(f'"{f}"' for f in s.files)
        lines.append(f'        "{s.name}": (')
        lines.append(f'            files: [{files}],')
        lines.append(f'            category: "{s.category}",')
        lines.append('            volume: 1.00,')
        lines.append(f'            looping: {"true" if s.loop else "false"},')
        lines.append(f'            pitch: ({s.pitch[0]:.3f}, {s.pitch[1]:.3f}),')
        lines.append(f'            lufs: {s.target:.1f},')
        lines.append(f'            sequence: {"true" if s.sequence else "false"},')
        lines.append(f'            stereo: {"true" if s.stereo else "false"},')
        lines.append('        ),' + (f' // {s.notes}' if s.notes else ''))
    lines += ['    },'] + sounds_streak.manifest_section() + [')', '']
    return '\n'.join(lines)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--only', nargs='*', help='sound ids to (re)generate (manifest still lists all)')
    ap.add_argument('--format', choices=['ogg', 'wav'], default='ogg')
    ap.add_argument('--out', type=Path, default=OUT_DIR)
    ap.add_argument('--list', action='store_true')
    args = ap.parse_args(argv)

    if args.list:
        for s in REGISTRY.values():
            print(f'{s.name:22s} {s.category:12s} x{s.variations:<2d} {s.target:6.1f} LUFS '
                  f'{"loop " if s.loop else ""}{"stereo" if s.stereo else ""}')
        return
    args.out.mkdir(parents=True, exist_ok=True)
    if args.only:
        unknown = set(args.only) - set(REGISTRY)
        if unknown:
            sys.exit(f'unknown sound ids: {sorted(unknown)}')
    else:
        # full regen: remove stale generated audio so renamed/removed sounds don't linger
        for p in list(args.out.glob('*.ogg')) + list(args.out.glob('*.wav')):
            p.unlink()

    t0 = time.time()
    print(f'{"file":28s} {"dur":>5s} {"peak":>6s} {"rms":>6s} {"LUFS":>6s} {"tgt":>5s}')
    for s in REGISTRY.values():
        s.files = [f'sfx/{s.name}_{v + 1}.{args.format}' for v in range(s.variations)]
        if args.only and s.name not in args.only:
            continue
        for v in range(s.variations):
            rng = np.random.default_rng(seed_for(s.name, v))
            dsp.CUT_WARNINGS.clear()
            md = s.max_dur[v] if isinstance(s.max_dur, (list, tuple)) else s.max_dur
            target = s.target + s.lufs_ramp * v
            y = s.fn(rng, v)
            if s.stereo != (np.ndim(y) == 2):
                sys.exit(f'{s.name}: stereo={s.stereo} but recipe returned shape {np.shape(y)}')
            x, info = master(y, s.loop, target, args.format, md, s.fade_out)
            for w in dict.fromkeys(dsp.CUT_WARNINGS):
                print(f'  warning {s.name}_{v + 1}: {w}')
            path = args.out / f'{s.name}_{v + 1}.{args.format}'
            (write_loop if s.loop else write)(path, x, args.format, rng)
            flag = '  (peak-capped)' if info['short_of_target'] > 0.5 else ''
            print(f'{path.name:28s} {info["dur"]:5.2f} {info["peak_db"]:6.1f} {info["rms_db"]:6.1f} '
                  f'{info["lufs"]:6.1f} {target:5.1f}{flag}')
    (args.out / 'manifest.ron').write_text(manifest(REGISTRY.values(), args.format), encoding='utf-8')
    print(f'done in {time.time() - t0:.1f}s -> {args.out}')


if __name__ == '__main__':
    main()
