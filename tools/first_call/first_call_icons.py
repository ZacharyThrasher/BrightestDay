"""FIRST CALL / BURN ON DEATH: derive assets/first_call_icons.ron from the icon files.

Every curated icon (assets/icons.ron + assets/icons/*.ron) is a NAMED famous thing a player can own
under the FIRST CALL match rule (bd_sim::first_call), except the generic ones:
  * sources that are generic vocabulary (military terms, D&D SRD spells, table talk, the lantern's own
    basic constructs, cartoon gags, plain mythology / folklore creature types), and
  * a short hand list of single everyday words (a dragon, a slime, a t-rex, tnt...).
Rows: (canonical name = names[0], display name = recipe.name, icon id or "", procedural seed or 0).

  python tools/first_call/first_call_icons.py           # rewrite the file
  python tools/first_call/first_call_icons.py --check   # exit 1 if it is stale (bd_sim tests check too)

Re-run after adding icons. The rules live here and in bd_sim/tests/first_call.rs (same filters).
"""
import glob
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT = os.path.join(ROOT, "assets", "first_call_icons.ron")

# A source containing any of these (case-insensitive) is generic vocabulary, not a named thing.
GENERIC_SOURCES = [
    "generic", "military", "srd", "table talk", "dc (green lantern)", "cartoon gag", "kitchen", "astrophysics",
    "medieval", "cartoon sci-fi", "telescoping weapons", "folklore", "bowling", "festival tradition", "paleontology",
]
# Exact sources that are generic (a bare "Mythology" is a dragon, not a named myth).
GENERIC_EXACT = ["mythology"]
# Canonical names that are everyday words even though a franchise drew them.
GENERIC_NAMES = [
    "dragon", "slime", "t-rex", "tnt", "black hole", "frying pan", "boxing glove", "ball and chain", "shrink ray",
    "creeper", "kraken", "hydra", "velociraptor", "minion", "symbiote", "ghost trap", "freeze ray", "growth ray",
    "tractor beam", "hoverboard", "wingsuit", "c4", "sticky bomb", "care package", "cardboard box", "firecrackers",
    "sky lanterns", "stone lions", "great wall", "terracotta army", "angry bird", "tetris block", "space invader",
]


def generic(source, name):
    s = source.lower()
    return any(g in s for g in GENERIC_SOURCES) or s in GENERIC_EXACT or name in GENERIC_NAMES


def rows():
    files = [os.path.join(ROOT, "assets", "icons.ron")] + sorted(glob.glob(os.path.join(ROOT, "assets", "icons", "*.ron")))
    out = []
    seen = set()
    for f in files:
        src = open(f, encoding="utf-8").read()
        for part in src.split("IconEntry(")[1:]:
            names = re.search(r'names:\s*\[\s*"([^"]+)"', part)
            disp = re.search(r'recipe:\s*\(\s*name:\s*"([^"]*)"', part)
            source = re.search(r'source:\s*"([^"]*)"', part)
            icon = re.search(r'model:\s*Icon\("([^"]+)"\)', part)
            seed = re.search(r'model:\s*Procedural\(seed:\s*(\d+)\)', part)
            if not names or not disp:
                continue
            canon = names.group(1).strip().lower()
            if generic(source.group(1) if source else "", canon) or canon in seen:
                continue
            seen.add(canon)
            out.append((canon, disp.group(1), icon.group(1) if icon else "", int(seed.group(1)) if (seed and not icon) else 0))
    return out


def render(rs):
    lines = [
        "// GENERATED by tools/first_call/first_call_icons.py -- do not edit; re-run after changing icons.",
        "// FIRST CALL / BURN ON DEATH (bd_sim::first_call): every NAMED curated icon a player can own.",
        "// (canonical name, display name, icon id or \"\", procedural seed or 0)",
        "[",
    ]
    for c, d, i, s in rs:
        esc = lambda x: x.replace("\\", "\\\\").replace('"', '\\"')
        lines.append('    ("%s", "%s", "%s", %d),' % (esc(c), esc(d), esc(i), s))
    lines.append("]")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    text = render(rows())
    if "--check" in sys.argv:
        cur = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if cur.replace("\r\n", "\n") != text:
            print("assets/first_call_icons.ron is stale: run python tools/first_call/first_call_icons.py")
            sys.exit(1)
        print("first_call_icons.ron up to date")
    else:
        with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
        print("wrote %s (%d named icons)" % (OUT, text.count("\n    (")))
