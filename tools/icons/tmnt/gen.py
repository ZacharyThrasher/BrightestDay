"""Generate assets/icons/tmnt.ron (Teenage Mutant Ninja Turtles pack).

    python tools/icons/tmnt/gen.py                     -> assets/icons/tmnt.ron
    python tools/icons/tmnt/render.py [ids] [--rows]   -> scratch contact sheet
Validate: cargo run --manifest-path tools/iconcheck/Cargo.toml -- assets/icons/tmnt.ron
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from tlib import ROOT, entry_ron  # noqa: E402
import chars  # noqa: E402

MODULES = [chars]
for extra in ("villains", "things"):
    try:
        MODULES.append(__import__(extra))
    except ModuleNotFoundError:
        pass


def entries():
    out = []
    for m in MODULES:
        for f in m.build_all():
            out.append(f())
    return out


def main():
    lines = [
        "// Brightest Day - Teenage Mutant Ninja Turtles pack (1987 cartoon, Mirage, 2003, 2012, Rise, Mutant",
        "// Mayhem, IDW, games, films). Generated by tools/icons/tmnt/gen.py - edit the generator, not this file.",
        "// Accent = each character's signature colour (turtle masks: Leo blue, Raph red, Donnie purple,",
        "// Mikey orange). Creatures use parts 1/2 legs, 3/4 arms, 5 head, 6 jaw, 7 cloth, 8+ tail, 255 seat.",
        "[",
    ]
    seen = {}
    n_shape = 0
    for names, recipe, shape, note in entries():
        for n in names:
            assert n not in seen, "duplicate name %r (%s / %s)" % (n, seen[n], names[0])
            seen[n] = names[0]
        if shape is not None:
            n_shape += 1
            recipe.setdefault("icon", names[0].replace(" ", "_").replace("'", ""))
        else:
            recipe.pop("icon", None)
        lines.append(entry_ron(names, recipe, shape, source=recipe.pop("source", "Teenage Mutant Ninja Turtles"), note=note))
    lines.append("]")
    path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "assets", "icons", "tmnt.ron")
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")
    print("wrote %s: %d entries, %d with shapes, %d names" % (path, len(lines) - 6, n_shape, len(seen)))


if __name__ == "__main__":
    main()
