"""Generate assets/icons/dc.ron (DC / Invincible / other superhero IP pack).

    python tools/icons/dc/gen.py                      -> assets/icons/dc.ron
    python tools/icons/dc/render.py [ids] [--rows]    -> scratch contact sheet (real bd_shapes voxeliser)
    sh tools/icons/dc/run.sh                          -> gen + iconcheck + render
Validate: cargo run --manifest-path tools/iconcheck/Cargo.toml -- assets/icons/dc.ron

Every name is checked against every other icon pack + powers.ron names (tools/icons/dc/dlib.taken_names):
a clash aborts generation, so dc.ron never shadows/duplicates another pack. Overlaps with existing DC items
are documented in tools/icons/dc/overlaps.txt.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from dlib import ROOT, entry_ron, taken_names, norm_name  # noqa: E402
import justice  # noqa: E402

MODULES = [justice]
for extra in ("league", "gotham", "lanterns", "cosmic", "image", "others", "procs"):
    try:
        MODULES.append(__import__(extra))
    except ModuleNotFoundError:
        pass


def entries():
    out = []
    for m in MODULES:
        for f in m.build_all():
            out.append(f())
    return out


def main():
    lines = [
        "// Brightest Day - DC / Invincible / superhero pack (Justice League, Batman & Superman families, the",
        "// emotional-spectrum Lantern Corps, Teen Titans, New Gods, Invincible, The Boys, Power Rangers, Ben 10,",
        "// Powerpuff Girls, Hellboy, Spawn, The Incredibles, Megamind, Static Shock, The Tick...).",
        "// Generated by tools/icons/dc/gen.py - edit the generator, not this file. Names/facts only.",
        "// Accent = the character's signature colour. Creatures: parts 1/2 legs, 3/4 arms, 5 head, 6 jaw,",
        "// 7 cloth (capes), 8+ tail, 12/13 wings, 255 seat. Flight stays a creature/vehicle verb here; player",
        "// flight lives in assets/powers.ron (thrust_max <= 17 m/s).",
        "[",
    ]
    taken = taken_names()
    seen = {}
    n_shape = n_alt = 0
    clashes = []
    for item in entries():
        names, recipe, shape, note = item[:4]
        alt = item[4] if len(item) > 4 else None
        for n in names:
            assert n not in seen, "duplicate name %r (%s / %s)" % (n, seen[n], names[0])
            seen[n] = names[0]
            k = norm_name(n)
            if n in taken or k in taken:
                clashes.append("%r (%s) taken by %s" % (n, names[0], taken.get(n) or taken.get(k)))
        if shape is not None:
            n_shape += 1
            recipe.setdefault("icon", names[0])
        else:
            recipe.pop("icon", None)
        if alt is not None:
            n_alt += 1
        lines.append(entry_ron(names, recipe, shape, source=recipe.pop("source", "DC"), note=note, alt=alt))
    if clashes:
        print("NAME CLASHES with other packs:\n  " + "\n  ".join(clashes))
        sys.exit(2)
    lines.append("]")
    path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "assets", "icons", "dc.ron")
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")
    print("wrote %s: %d entries, %d with shapes, %d two-mode, %d names" % (
        path, sum(l.count("    IconEntry(") for l in lines), n_shape, n_alt, len(seen)))


if __name__ == "__main__":
    main()
