"""Write assets/icons/dc_names.txt from names_data.py (validated).

    python tools/icons/dc/names_gen.py

Line format: name | aliases (;) | Wikidata QID (blank = unresolved) | hint: Form + mechanics, element, temperament [notes]
Checks: every name/alias is lowercase, unique, not already an icon in any pack (incl. dc.ron) nor a power name;
the hint's Form and tags are from the closed sets in bd_core/src/mechanics.rs. Taken names are dropped (logged).
QIDs are left blank on purpose: no web lookups were made for this list (the lexicon build resolves them).
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from dlib import ROOT, FORMS, MECH_ORDER, FEAT_ORDER, TEMPS, ELEMS, taken_names, norm_name  # noqa: E402
from names_data import GROUPS  # noqa: E402

TAGS = set(MECH_ORDER) | set(FEAT_ORDER) | TEMPS | ELEMS


def main():
    taken = taken_names(exclude=())      # every pack, dc.ron included
    pend = open(os.path.join(ROOT, "assets", "powers.ron"), encoding="utf-8").read()  # pending file merged
    for m in re.finditer(r"names:\s*\[(.*?)\]", pend, re.S):
        for n in re.findall(r'"([^"]*)"', m.group(1)):
            taken.setdefault(norm_name(n), "powers.ron")
    seen = set()
    out = [
        "# Brightest Day - DC / Invincible / superhero names (2026-09): DC (Superman & Batman families, Wonder Woman, Flash,",
        "# the emotional-spectrum Corps, Aquaman, JLA/JSA, Titans, Doom Patrol, New Gods, Legion, Vertigo, Watchmen),",
        "# Invincible, The Boys, Power Rangers, Ben 10, Powerpuff Girls, Hellboy, Spawn/Image, The Incredibles, Megamind,",
        "# Static/Milestone, Kick-Ass, The Umbrella Academy, The Tick, other movie supers. Names and facts only.",
        "# name | aliases (;) | Wikidata QID (blank = unresolved) | hint: Form + mechanics, element, temperament [notes]",
        "# Hand-authored icons live in dc.ron; nothing here duplicates any icon pack or power name.",
        "# Generated by tools/icons/dc/names_gen.py from names_data.py. QIDs deliberately blank (no web lookups).",
    ]
    n_names = dropped = 0
    errors = []
    for group, block in GROUPS.items():
        lines = []
        for raw in block.strip().splitlines():
            parts = [p.strip() for p in raw.split("|")]
            while len(parts) < 3:
                parts.append("")
            name, aliases, hint = parts[0], parts[1], "|".join(parts[2:]).strip()
            if not hint:
                print("skip (no hint):", name)
                dropped += 1
                continue
            m = re.match(r"([A-Za-z0-9]+)\s*\+?\s*([^\[]*)(\[.*\])?$", hint)
            assert m, (name, hint)
            form = m.group(1)
            if form not in FORMS:
                errors.append("%s: form %r" % (name, form))
            for tok in [t.strip() for t in m.group(2).split(",") if t.strip()]:
                if not (tok in TAGS or re.fullmatch(r"Count \d+", tok)):
                    errors.append("%s: tag %r" % (name, tok))
            al = [a.strip() for a in aliases.split(";") if a.strip()]
            keep = []
            for n in [name] + al:
                assert n == n.lower(), n
                k = norm_name(n)
                if n in taken or k in taken or k in seen:
                    print("drop %r (%s)" % (n, taken.get(n) or taken.get(k) or "dup"))
                    continue
                seen.add(k)
                keep.append(n)
            if not keep or keep[0] != name:
                if not keep:
                    dropped += 1
                    continue
            n_names += 1
            lines.append("%s | %s |  | hint: %s" % (keep[0], "; ".join(keep[1:]), hint))
        out.append("")
        out.append("# " + group)
        out += lines
    if errors:
        print("HINT ERRORS:\n  " + "\n  ".join(errors))
        sys.exit(2)
    path = os.path.join(ROOT, "assets", "icons", "dc_names.txt")
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(out) + "\n")
    print("wrote %s: %d names (%d dropped)" % (path, n_names, dropped))


if __name__ == "__main__":
    main()
