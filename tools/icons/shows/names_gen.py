"""Generate assets/icons/shows_names.txt from tools/icons/shows/names_data.py.

    python tools/icons/shows/names_gen.py

Data lines: `name; alias; alias = Form Mechanic ... [Element] [Temperament] [Feature]`. Every hint token is validated
against bd_core's closed sets. A line whose name is already used by any icon pack / powers.ron / *_names.txt
(shows.ron included) is skipped; taken aliases are dropped. Output format (consumed by tools/lexicon_build):
`name | alias; alias | QID | hint: Form + Mechanics`.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from slib import ROOT, taken_names, norm_name, FORMS, MECH_ORDER, FEAT_ORDER, TEMPS, ELEMS  # noqa: E402
from names_data import DATA  # noqa: E402

HEADER = """# Brightest Day - TV & movie names (2026-09): adult animation, sitcoms, prestige TV, horror, action films, family
# animation, kids' TV, game shows, Dune, 2024-26 hits. Generated by tools/icons/shows/names_gen.py (edit names_data.py).
# Format: name | alias; alias | QID | hint: Form + mechanics [element] [temperament]. Names/facts only.
# Nothing here duplicates a name in any icon pack, powers.ron or another *_names.txt (checked at generation)."""


def main():
    taken = taken_names(exclude=())
    out, seen, skipped, dropped = [], set(), [], 0
    for sec, block in DATA:
        lines = []
        for raw in block.strip().split("\n"):
            raw = raw.strip()
            if not raw or raw.startswith("#"):
                continue
            left, hint = raw.split("=", 1)
            names = [n.strip().lower() for n in left.split(";") if n.strip()]
            toks = hint.split()
            form = [t for t in toks if t in FORMS]
            assert len(form) == 1, (raw, form)
            for t in toks:
                assert t in FORMS or t in MECH_ORDER or t in FEAT_ORDER or t in TEMPS or t in ELEMS, (raw, t)
            name, aliases = names[0], names[1:]
            if name in taken or norm_name(name) in taken or norm_name(name) in seen:
                skipped.append("%s (%s)" % (name, taken.get(name) or taken.get(norm_name(name)) or "dup"))
                continue
            seen.add(norm_name(name))
            keep = []
            for a in aliases:
                k = norm_name(a)
                if a in taken or k in taken or k in seen:
                    dropped += 1
                    continue
                seen.add(k)
                keep.append(a)
            mech = [t for t in toks if t in MECH_ORDER]
            rest = [t for t in toks if t not in FORMS and t not in MECH_ORDER]
            h = form[0] + (" + " + ", ".join(mech) if mech else "") + ("".join(" " + r for r in rest))
            lines.append("%s | %s |  | hint: %s" % (name, "; ".join(keep), h))
        if lines:
            out.append("# --- " + sec)
            out.extend(lines)
    path = os.path.join(ROOT, "assets", "icons", "shows_names.txt")
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(HEADER + "\n" + "\n".join(out) + "\n")
    n = sum(1 for l in out if not l.startswith("#"))
    print("wrote %s: %d names (%d lines skipped as taken, %d aliases dropped)" % (path, n, len(skipped), dropped))
    with open(os.path.join(HERE, "names_skipped.txt"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(skipped) + "\n")


if __name__ == "__main__":
    main()
