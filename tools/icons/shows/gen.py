"""Generate assets/icons/shows.ron (popular TV shows & movies not covered by the other packs: adult animation,
sitcoms, prestige TV, slasher/horror, action films, family animation, game/reality shows, Dune, 2024-26 hits).

    python tools/icons/shows/gen.py              -> assets/icons/shows.ron (+ tools/icons/shows/overlaps.txt)
    python tools/icons/shows/render.py [ids]     -> scratch contact sheet (real bd_shapes voxeliser, dcview)
    python tools/icons/shows/names_gen.py        -> assets/icons/shows_names.txt
Validate: cargo run --manifest-path tools/iconcheck/Cargo.toml -- assets/icons/shows.ron

Every name is checked against every other icon pack, powers.ron AND every other *_names.txt (normalised):
a taken alias is dropped and logged in overlaps.txt; a taken canonical id aborts generation.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from slib import ROOT, entry_ron, taken_names, norm_name  # noqa: E402
import reg  # noqa: E402

MODULES = ["toons", "sitcoms", "prestige", "horror", "action", "family", "gameshows", "dune"]


def main():
    for m in MODULES:
        __import__(m)
    lines = [
        "// Brightest Day - TV & movie pack: adult animation (Simpsons, Family Guy, South Park, Futurama, Rick and",
        "// Morty, Bob's Burgers, King of the Hill, Archer), sitcoms (The Office, Parks and Rec, Friends, Seinfeld,",
        "// Brooklyn 99, Always Sunny, Arrested Development), prestige TV (Breaking Bad, Game of Thrones, The Last of",
        "// Us, Squid Game, Fallout, The Witcher, Peaky Blinders, The Walking Dead, Wednesday), slashers, action films,",
        "// family animation (Toy Story, Up, Cars, Inside Out, Frozen, Encanto, Kung Fu Panda, HTTYD, Wicked...),",
        "// game shows / TV icons, Dune. Generated by tools/icons/shows/gen.py - edit the generator, not this file.",
        "// Names/facts only. Parts: 1/2 legs (1..4 on quadrupeds), 3/4 arms, 5 head, 6 jaw, 7 cloth, 8+ tail,",
        "// 12/13 wings, 20+ wheels, 255 seat. Accent = the character's signature colour.",
        "[",
    ]
    taken = taken_names()
    seen = {}
    n_shape = n_names = 0
    dropped, fatal = [], []
    for f in reg.E:
        names, recipe, shape, note = f()
        keep = []
        for n in names:
            assert n == n.lower() and n.strip(), n
            k = norm_name(n)
            owner = taken.get(n) or taken.get(k)
            if owner:
                (fatal if n == names[0] else dropped).append("%-34s (%s) taken by %s" % (repr(n), names[0], owner))
                continue
            if (seen.get(n) or seen.get(k)) == names[0]:
                continue                     # same entry, same normalised spelling
            if n in seen or k in seen:
                fatal.append("%r duplicated inside shows.ron (%s / %s)" % (n, seen.get(n) or seen.get(k), names[0]))
                continue
            seen[n] = seen[k] = names[0]
            keep.append(n)
        if not keep or keep[0] != names[0]:
            continue
        n_names += len(keep)
        if shape is not None:
            n_shape += 1
            recipe.setdefault("icon", names[0])
        else:
            recipe.pop("icon", None)
        lines.append(entry_ron(keep, recipe, shape, source=recipe.pop("source", "TV / Film"), note=note))
    with open(os.path.join(HERE, "overlaps.txt"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write("# shows.ron aliases dropped because another pack / names.txt already owns them (regenerated by gen.py)\n")
        fh.write("\n".join(dropped) + "\n")
    if fatal:
        print("FATAL name clashes:\n  " + "\n  ".join(fatal))
        sys.exit(2)
    lines.append("]")
    path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "assets", "icons", "shows.ron")
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")
    print("wrote %s: %d entries, %d with shapes, %d names (%d aliases dropped, see overlaps.txt)" % (
        path, sum(l.count("    IconEntry(") for l in lines), n_shape, n_names, len(dropped)))


if __name__ == "__main__":
    main()
