"""Generate assets/icons/pokemon.ron from the shape modules in this folder.

    python tools/icons/pokemon/gen.py                 # all modules -> assets/icons/pokemon.ron
    python tools/icons/pokemon/gen.py --check         # also report names that collide with other icon files
    python tools/icons/pokemon/render.py id,id --rows # contact sheet with the real bd_shapes voxeliser
Modules: each `mons_*.py` / `items.py` defines register() that calls plib.icon(...). A module that fails to
import is reported and skipped (so one broken batch never blocks the others).
"""
import glob
import importlib
import os
import re
import sys
import traceback

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
ROOT = os.environ.get("BD_ROOT") or os.path.abspath(os.path.join(HERE, "..", "..", ".."))
import plib  # noqa: E402

OUT = os.path.join(ROOT, "assets", "icons", "pokemon.ron")
MODULES = ["items", "mons_starters", "mons_favs", "mons_legends", "mons_extra"]


def other_icon_names():
    """names -> file for every icon file except ours (assets/icons.ron + assets/icons/*.ron)."""
    files = [os.path.join(ROOT, "assets", "icons.ron")] + sorted(glob.glob(os.path.join(ROOT, "assets", "icons", "*.ron")))
    out = {}
    for p in files:
        if os.path.basename(p) == "pokemon.ron":
            continue
        txt = open(p, encoding="utf-8").read()
        for m in re.finditer(r"names:\s*\[([^\]]*)\]", txt):
            for n in re.findall(r'"([^"]*)"', m.group(1)):
                out.setdefault(n, os.path.basename(p))
    return out


def main():
    check = "--check" in sys.argv
    ok = True
    for name in MODULES:
        if not os.path.exists(os.path.join(HERE, name + ".py")):
            continue
        try:
            mod = importlib.import_module(name)
            n0 = len(plib.E)
            mod.register()
            print(f"  {name}: {len(plib.E) - n0} icons")
        except Exception:
            ok = False
            print(f"  !! module {name} failed:")
            traceback.print_exc()
    E = plib.E
    others = other_icon_names()
    seen, ids = {}, set()
    for e in E:
        assert e['id'] not in ids, "duplicate id " + e['id']
        ids.add(e['id'])
        keep = []
        for n in e['names']:
            if n in others:
                print(f"  drop name '{n}' of [{e['id']}]: already an icon in {others[n]}")
                continue
            if n in seen and seen[n] != e['id']:
                print(f"  DUP NAME '{n}' in [{e['id']}] and [{seen[n]}] (kept on the first)")
                continue
            seen[n] = e['id']
            keep.append(n)
        assert keep, f"[{e['id']}] has no names left"
        e['names'] = keep
        if e['shape'] is not None:
            n = len(e['shape'].prims)
            if n > 110:
                print(f"  WARN [{e['id']}] {n} prims")
    head = ("// Brightest Day - Pokemon icon pack (curated 2026-09). Schema: docs/ICONS_SCHEMA.md.\n"
            "// Names only; recipes use the closed bd_core sets. Generated by tools/icons/pokemon/gen.py - edit the\n"
            "// generator, not this file.\n")
    body = "[\n" + "\n".join(plib.entry_ron(e) for e in E) + "\n]\n"
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(head + body)
    shaped = sum(1 for e in E if e['shape'] is not None)
    print(f"wrote {OUT}: {len(E)} entries ({shaped} hand-shaped)")
    if check:
        print("ids:", ", ".join(e['id'] for e in E))
    if not ok:
        sys.exit(1)


if __name__ == "__main__":
    main()
