FWD = (-90, 0, 0)  # cone tip -> -Z


def legs4(s, y, x, zf, zb, size, t="D", first=10):
    roles = [("LegFrontLeft", -x, zf), ("LegFrontRight", x, zf), ("LegBackLeft", -x, zb), ("LegBackRight", x, zb)]
    for i, (role, lx, lz) in enumerate(roles):
        pid = first + i
        s.part(pid, 0, (lx, y, lz), role)
        s.box((lx, y / 2, lz), (size, y, size), t, pid)
    return s


def biped_legs(s, y, x, w, t="D", first=10, foot=None):
    for i, (role, lx) in enumerate([("LegBackLeft", -x), ("LegBackRight", x)]):
        pid = first + i
        s.part(pid, 0, (lx, y, 0), role)
        s.box((lx, y / 2, 0), (w, y, w), t, pid)
        if foot:
            s.box((lx, foot[1] / 2, -foot[2] / 2 + w / 2), foot[:3], t, pid)
    return s


