"""Generate assets/icons/transformers.ron (two-mode Transformers icons + items).

    python tools/icons/transformers/gen.py            -> assets/icons/transformers.ron
    python tools/icons/transformers/render.py [ids]   -> scratch contact sheet (alt | robot | back | walk)

Validate: cargo run --manifest-path tools/iconcheck/Cargo.toml -- assets/icons/transformers.ron
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
ROOT = os.path.abspath(os.path.join(HERE, "..", "..", ".."))

from tflib import entry_ron, robot_height_m  # noqa: E402
import bots_a  # noqa: E402
import bots_cars  # noqa: E402
import bots_vans  # noqa: E402
import bots_d  # noqa: E402
import bots_beasts  # noqa: E402
import bots_giants  # noqa: E402
import items  # noqa: E402
import bots_more  # noqa: E402

BUILDERS = [
    bots_a.optimus_prime,
    bots_cars.bumblebee,
    bots_vans.jazz,
    bots_vans.ironhide,
    bots_vans.ratchet,
    bots_vans.arcee,
    bots_vans.wheeljack,
    bots_vans.bulkhead,
    bots_d.megatron,
    bots_d.starscream,
    bots_d.soundwave,
    bots_d.shockwave,
    bots_more.sideswipe,
    bots_more.prowl,
    bots_more.hot_rod,
    bots_more.cliffjumper,
    bots_more.mirage,
    bots_more.nemesis_prime,
    bots_more.thundercracker,
    bots_more.skywarp,
    bots_beasts.grimlock,
    bots_beasts.optimus_primal,
    bots_giants.devastator,
    bots_giants.unicron,
    items.laserbeak,
    items.ravage,
    items.energon_cube,
    items.matrix_of_leadership,
    items.star_saber,
    items.energon_axe,
    items.fusion_cannon,
    items.allspark,
]


def main():
    out = [
        "// Brightest Day - Transformers pack (a birthday present: make it great). Generated by",
        "// tools/icons/transformers/gen.py - edit the generator, not this file.",
        "// Two-mode icons: `shape` = alt mode (vehicle/beast/boombox...), `alt_shape` = robot mode. Shared",
        "// panels keep the same part id AND the same prims (rigidly moved) in both modes, so the",
        "// transformation can fold each panel; robot-only parts (head, arms, weapons) have their own ids.",
        "[",
    ]
    for f in BUILDERS:
        res = f()
        names, recipe, model, note = res[:4]
        if hasattr(model, "robot"):
            rh, alt = robot_height_m(model, recipe["form"], recipe["scale"])
            print("%-22s robot %.1f m  alt %.1f x %.1f x %.1f m  prims %d/%d" % (names[0], rh, alt[0], alt[1], alt[2],
                  len(model.alt.prims), len(model.robot.prims)))
            out.append(entry_ron(names, recipe, tf=model, comment=note))
        else:
            out.append(entry_ron(names, recipe, shape=model, comment=note))
    out.append("]")
    path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "assets", "icons", "transformers.ron")
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(out) + "\n")
    print("wrote", path, len(BUILDERS), "entries")


if __name__ == "__main__":
    main()
