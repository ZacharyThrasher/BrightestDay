"""Generate crates/bd_lexicon/src/tables.rs from bd_core's closed enums.

Run after adding a variant to Form / Mechanic / Feature / Element / Temperament in bd_core:
    python tools/lexicon_build/gen_tables.py
The generated matches are exhaustive, so forgetting to regenerate is a compile error, not silent data loss.
"""
import re
from pathlib import Path

GAME = Path(__file__).resolve().parent.parent.parent
src = (GAME / "crates/bd_core/src/mechanics.rs").read_text(encoding="utf-8")


def variants(name):
    m = re.search(r"pub enum " + name + r" \{(.*?)\n\}", src, re.S)
    body = re.sub(r"//[^\n]*", "", m.group(1))
    out = []
    for v in body.split(","):
        v = v.replace("#[default]", "").strip()
        if v:
            out.append(v.split("(")[0].split("{")[0].strip())
    return out


enums = {n: variants(n) for n in ["Form", "Mechanic", "Feature", "Element", "Temperament"]}
lines = [
    "//! GENERATED by tools/lexicon_build/gen_tables.py from bd_core::mechanics — do not edit by hand.",
    "//! Stable indices for the closed enums (used as bit positions / bytes in lexicon.bin).",
    "#![allow(clippy::all)]",
    "use bd_core::mechanics::{Element, Feature, Form, Mechanic, Temperament};",
    "",
]
for name, vs in enums.items():
    up = name.upper()
    lines.append(f"pub const ALL_{up}: [{name}; {len(vs)}] = [")
    for v in vs:
        lines.append(f"    {name}::{v},")
    lines.append("];")
    fn = name.lower()
    lines.append(f"#[inline]\npub fn {fn}_index(x: {name}) -> u8 {{\n    match x {{")
    for i, v in enumerate(vs):
        lines.append(f"        {name}::{v} => {i},")
    lines.append("    }\n}")
    lines.append(f"pub fn {fn}_from_name(s: &str) -> Option<{name}> {{\n    Some(match s {{")
    for v in vs:
        lines.append(f'        "{v}" => {name}::{v},')
    lines.append("        _ => return None,\n    })\n}")
    lines.append(f"pub fn {fn}_name(x: {name}) -> &'static str {{\n    match x {{")
    for v in vs:
        lines.append(f'        {name}::{v} => "{v}",')
    lines.append("    }\n}")
    lines.append("")
out = GAME / "crates/bd_lexicon/src/tables.rs"
out.write_text("\n".join(lines), encoding="utf-8", newline="\n")
print(f"wrote {out}: " + ", ".join(f"{k}={len(v)}" for k, v in enums.items()))
