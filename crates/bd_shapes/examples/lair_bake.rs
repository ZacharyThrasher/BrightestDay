//! Bake Turtle Lair decor props from the construct icon/shape library into terrain-voxel models.
//!
//! ```text
//! cargo run -p bd_shapes --example lair_bake --release
//! ```
//! Same pipeline as `backrooms_bake`: the curated icon library resolves each phrase, the spec is
//! scaled (to a target height, or to a target longest side for flat/long things like a pizza or a
//! skateboard), voxelised at 0.5 m with every part in rest pose, and written with its tints to
//! `crates/bd_voxel/src/maps/lair_icons.rs` (the map maps tints to terrain materials per prop).
//! Also writes a contact sheet to `target/lair/icon_props.png`.

use std::fmt::Write as _;
use std::path::PathBuf;

use bd_core::shape::Tint;
use bd_shapes::{generate, spec_bounds, voxelize_at};
use glam::IVec3;

/// How a prop's size is given.
#[derive(Clone, Copy)]
enum Fit {
    /// Target height (m).
    Height(f32),
    /// Target longest side (m).
    Longest(f32),
}

/// (name in the map, phrase, size).
const PROPS: &[(&str, &str, Fit)] = &[
    // The big neon pizza sign over the arcade corner (mounted flat against the wall).
    ("pizza sign", "tmnt pizza", Fit::Longest(4.5)),
    ("skateboard", "tmnt skateboard", Fit::Longest(2.6)),
    // The weapon rack (oversized on purpose so they read at 0.5 m).
    ("katanas", "leo's katanas", Fit::Longest(2.6)),
    ("sais", "raph's sais", Fit::Longest(2.0)),
    ("bo staff", "donnie's bo staff", Fit::Longest(3.4)),
    ("nunchucks", "mikey's nunchucks", Fit::Longest(2.0)),
    // Lab + garage.
    ("krang android", "krang's android body", Fit::Height(4.4)),
    ("party wagon", "turtle van", Fit::Longest(7.5)),
    ("ooze canister", "ooze canister", Fit::Height(1.6)),
    ("mouser", "mouser robot", Fit::Height(1.2)),
    // A derelict subway car on the station platform.
    ("shellraiser", "shellraiser", Fit::Longest(11.0)),
    ("manhole cover", "sewer manhole cover", Fit::Longest(2.0)),
    // Junk.
    ("shopping cart", "shopping cart", Fit::Height(1.5)),
];

fn main() {
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..");
    let lex = bd_lexicon::Lexicon::icons_only(&bd_lexicon::Lexicon::icon_files(&root.join("assets")));
    let mut out = String::new();
    out.push_str("//! GENERATED by `cargo run -p bd_shapes --example lair_bake --release` — do not edit.\n");
    out.push_str("//! Icon-library props voxelised at 0.5 m for the Turtle Lair decor (see lair_props.rs).\n\n");
    out.push_str("/// A baked icon: voxels `(x, y, z, tint)` with the minimum corner at 0, +Y up, the icon's front\n");
    out.push_str("/// towards +Z; tint 0 Primary, 1 Accent, 2 Dark, 3 Core.\n");
    out.push_str("pub struct Icon {\n    pub name: &'static str,\n    pub phrase: &'static str,\n    pub voxels: &'static [(i8, i8, i8, u8)],\n}\n\n");
    out.push_str("#[rustfmt::skip]\npub static ICONS: &[Icon] = &[\n");
    let mut sheet: Vec<(String, Vec<(IVec3, u8)>)> = Vec::new();
    for &(name, phrase, fit) in PROPS {
        let r = lex.resolve(phrase);
        assert!(r.shape.is_some(), "{phrase}: not a curated icon shape");
        let mut spec = r.shape.clone().unwrap_or_else(|| generate(&r.recipe));
        let b = spec_bounds(&spec);
        let ext = b.max - b.min;
        // Spec units are 0.25 m.
        let k = match fit {
            Fit::Height(h) => h / 0.25 / ext.y.max(0.1),
            Fit::Longest(l) => l / 0.25 / ext.max_element().max(0.1),
        };
        bd_shapes::scale_spec(&mut spec, k);
        let model = voxelize_at(&spec, 2);
        let mut vox: Vec<(IVec3, u8)> = Vec::new();
        for (i, part) in model.parts.iter().enumerate() {
            let inst = model.instances.get(i).copied();
            let (src, off) = match inst {
                Some(p) if p.source != i => (&model.parts[p.source], (p.offset / model.voxel_size).round().as_ivec3()),
                _ => (part, IVec3::ZERO),
            };
            for &(v, t) in &src.voxels {
                let t = match t {
                    Tint::Primary => 0,
                    Tint::Accent => 1,
                    Tint::Dark => 2,
                    Tint::Core => 3,
                };
                // Icons face −Z; the map wants the front towards +Z.
                let p = v + off;
                vox.push((IVec3::new(p.x, p.y, -p.z), t));
            }
        }
        vox.sort_by_key(|(p, _)| (p.y, p.z, p.x));
        vox.dedup_by_key(|(p, _)| *p);
        let lo = vox.iter().fold(IVec3::splat(i32::MAX), |a, (p, _)| a.min(*p));
        let hi = vox.iter().fold(IVec3::splat(i32::MIN), |a, (p, _)| a.max(*p));
        for (p, _) in &mut vox {
            *p -= lo;
        }
        let size = hi - lo + IVec3::ONE;
        assert!(size.max_element() < 127, "{name}: too big for i8 voxels");
        println!("{name:>16}: {:?} {}, {} voxels, {}x{}x{} (0.5 m)", r.recipe.form, r.recipe.name, vox.len(), size.x, size.y, size.z);
        let _ = writeln!(out, "    Icon {{ name: {name:?}, phrase: {phrase:?}, voxels: &[");
        let mut line = String::from("        ");
        for (p, t) in &vox {
            let _ = write!(line, "({}, {}, {}, {t}), ", p.x, p.y, p.z);
            if line.len() > 120 {
                let _ = writeln!(out, "{}", line.trim_end());
                line = String::from("        ");
            }
        }
        if !line.trim().is_empty() {
            let _ = writeln!(out, "{}", line.trim_end());
        }
        out.push_str("    ] },\n");
        sheet.push((name.to_string(), vox));
    }
    out.push_str("];\n");
    let path = root.join("crates/bd_voxel/src/maps/lair_icons.rs");
    std::fs::write(&path, out).expect("write icons");
    println!("wrote {}", path.display());
    contact_sheet(&root.join("target/lair/icon_props.png"), &sheet);
}

/// Iso contact sheet: one tile per prop, tints Primary yellow / Accent orange / Dark grey / Core white.
fn contact_sheet(path: &std::path::Path, props: &[(String, Vec<(IVec3, u8)>)]) {
    let (tw, th) = (200u32, 220u32);
    let cols = 8u32;
    let rows = (props.len() as u32).div_ceil(cols);
    let mut img = image::RgbImage::from_pixel(tw * cols, th * rows, image::Rgb([20, 22, 28]));
    let pal = [[240.0, 200.0, 60.0], [240.0, 130.0, 40.0], [90.0, 90.0, 100.0], [250.0, 250.0, 250.0]];
    for (k, (_, vox)) in props.iter().enumerate() {
        let (col, row) = (k as u32 % cols, k as u32 / cols);
        let hi = vox.iter().fold(IVec3::ZERO, |a, (p, _)| a.max(*p));
        let s = (150.0 / (hi.x + hi.z + 2).max(hi.y + 2) as f32).clamp(1.0, 14.0);
        let mut sorted = vox.clone();
        sorted.sort_by_key(|(p, _)| (p.x + p.z, p.y));
        for (p, t) in sorted {
            let cx = tw as f32 * (col as f32 + 0.5) + (p.x - p.z) as f32 * s * 0.87;
            let cy = th as f32 * (row + 1) as f32 - 20.0 - (p.x + p.z) as f32 * s * 0.5 - p.y as f32 * s;
            let c = pal[t as usize];
            for (dy, shade) in [(0.0, 1.0), (s * 0.5, 0.75)] {
                for yy in 0..(s as i32).max(1) {
                    for xx in -(s as i32)..(s as i32) {
                        let (x, y) = (cx as i32 + xx, (cy + dy) as i32 + yy - s as i32);
                        if x >= 0 && y >= 0 && (x as u32) < img.width() && (y as u32) < img.height() {
                            let f = if xx < 0 { shade } else { shade * 0.85 };
                            img.put_pixel(x as u32, y as u32, image::Rgb([(c[0] * f) as u8, (c[1] * f) as u8, (c[2] * f) as u8]));
                        }
                    }
                }
            }
        }
    }
    std::fs::create_dir_all(path.parent().unwrap()).ok();
    img.save(path).expect("save sheet");
    println!("contact sheet {}", path.display());
}
