//! Write docs/LEXICON_REVIEW.md: the 50 lowest-confidence resolutions of the everyday phrase list
//! (tests/data/everyday_phrases.txt) plus any that miss their expected reading, for a human to eyeball.
//!
//!     CARGO_TARGET_DIR=target/lexicon cargo run --release -p bd_lexicon --example review

use std::fmt::Write as _;

fn main() {
    let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    let lex = match bd_lexicon::Lexicon::load(root.join("assets/lexicon.bin")) {
        Ok(l) => l,
        Err(e) => {
            eprintln!("load: {e}");
            std::process::exit(1);
        }
    };
    let list = include_str!("../tests/data/everyday_phrases.txt");
    let mut rows = Vec::new();
    for line in list.lines().map(str::trim).filter(|l| !l.is_empty() && !l.starts_with('#')) {
        let mut it = line.split('|').map(str::trim);
        let (Some(p), Some(want)) = (it.next(), it.next()) else { continue };
        let r = lex.resolve(p);
        rows.push((r.confidence, p.to_string(), want.to_string(), r));
    }
    rows.sort_by(|a, b| a.0.partial_cmp(&b.0).unwrap_or(std::cmp::Ordering::Equal).then(a.1.cmp(&b.1)));
    let mut md = String::new();
    let _ = writeln!(md, "# Lexicon review — lowest-confidence everyday phrases\n");
    let _ = writeln!(
        md,
        "Generated by `cargo run --release -p bd_lexicon --example review` from \
         `crates/bd_lexicon/tests/data/everyday_phrases.txt` ({} phrases). Fix a bad reading with an entry \
         in `tools/lexicon_build/everyday.py` (or `anchors.py`) and rebuild.\n",
        rows.len()
    );
    let _ = writeln!(md, "| # | phrase | conf | reading (form+mechanics/element) | expected | why |");
    let _ = writeln!(md, "|---|---|---|---|---|---|");
    for (i, (c, p, want, r)) in rows.iter().take(50).enumerate() {
        let why = r.explanation.first().cloned().unwrap_or_default().replace('|', "/");
        let _ = writeln!(md, "| {} | {} | {:.2} | `{}` | {} | {} |", i + 1, p, c, r.signature(), want, why);
    }
    let out = root.join("docs/LEXICON_REVIEW.md");
    match std::fs::write(&out, md) {
        Ok(()) => println!("wrote {} ({} phrases reviewed)", out.display(), rows.len()),
        Err(e) => eprintln!("write {}: {e}", out.display()),
    }
}
